/**
 * Generates src/core/generated/entity-sizes.ts: entity name → prototype type and
 * tile size, from Factorio's data dump. See docs/spec/03-game-assets.md
 * § Prototype data (fallback size table) and plan task 2.5.
 *
 * Usage (Node 24 runs this TypeScript directly):
 *   pnpm gen:sizes               # read an existing <write-data>/script-output/data-raw-dump.json
 *   pnpm gen:sizes --dump        # first run `factorio --dump-data` (Factorio must be closed)
 *
 * Environment:
 *   FACTORIO_PATH        game folder (default: D:\SteamLibrary\steamapps\common\Factorio
 *                        is NOT assumed; set it, or pass --factorio <path>)
 *   FACTORIO_WRITE_DATA  write-data folder (default: %APPDATA%\Factorio on Windows,
 *                        ~/.factorio on Linux, ~/Library/Application Support/factorio on macOS)
 *
 * Only names, types and sizes are written. No game assets are copied.
 */
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join } from 'node:path'
import { NOT_BLUEPRINTABLE_TYPES, tileSizeOf } from '../src/core/prototypes/blueprintable.ts'

const args = process.argv.slice(2)
const argValue = (flag: string): string | undefined => {
  const i = args.indexOf(flag)
  return i >= 0 ? args[i + 1] : undefined
}

function defaultWriteData(): string {
  if (process.platform === 'win32') return join(process.env['APPDATA'] ?? '', 'Factorio')
  if (process.platform === 'darwin')
    return join(homedir(), 'Library', 'Application Support', 'factorio')
  return join(homedir(), '.factorio')
}

const factorioPath = argValue('--factorio') ?? process.env['FACTORIO_PATH']
const writeData =
  argValue('--write-data') ?? process.env['FACTORIO_WRITE_DATA'] ?? defaultWriteData()
const dumpFile = join(writeData, 'script-output', 'data-raw-dump.json')

if (args.includes('--dump')) {
  if (!factorioPath) throw new Error('Set FACTORIO_PATH or pass --factorio <path> to run the dump.')
  const exe = join(
    factorioPath,
    'bin',
    'x64',
    process.platform === 'win32' ? 'factorio.exe' : 'factorio'
  )
  console.log(`Running ${exe} --dump-data …`)
  execFileSync(exe, ['--dump-data'], { stdio: 'inherit' })
}

if (!existsSync(dumpFile)) {
  throw new Error(`No dump at ${dumpFile}. Run with --dump (Factorio must be closed).`)
}

type Vec = [number, number] | { x: number; y: number }
type Prototype = {
  name: string
  type: string
  collision_box?: [Vec, Vec]
  tile_width?: number
  tile_height?: number
}

const raw = JSON.parse(readFileSync(dumpFile, 'utf8')) as Record<string, Record<string, Prototype>>

const baseInfo = factorioPath ? join(factorioPath, 'data', 'base', 'info.json') : undefined
const version =
  baseInfo && existsSync(baseInfo)
    ? (JSON.parse(readFileSync(baseInfo, 'utf8')) as { version: string }).version
    : 'unknown'

const sizes: Record<string, [string, number, number]> = {}
for (const [type, prototypes] of Object.entries(raw)) {
  if (NOT_BLUEPRINTABLE_TYPES.has(type)) continue
  for (const proto of Object.values(prototypes)) {
    if (!proto.collision_box && proto.tile_width === undefined) continue
    const { width, height } = tileSizeOf(proto)
    sizes[proto.name] = [type, width, height]
  }
}

const names = Object.keys(sizes).sort()
const body = names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(sizes[n])},`).join('\n')
const out = `// Generated by scripts/gen-entity-sizes.ts from the Factorio ${version} data dump. Do not edit.
// Names, prototype types and tile sizes only (no game assets).
// Mods at generation time: base game + expansions enabled in the developer's install.

export const ENTITY_SIZES_GAME_VERSION: string = ${JSON.stringify(version)}

/** name → [prototype type, tile width, tile height] (width/height for direction north). */
export const ENTITY_SIZES: Readonly<Record<string, readonly [string, number, number]>> = {
${body}
}
`
const target = join(import.meta.dirname, '..', 'src', 'core', 'generated', 'entity-sizes.ts')
writeFileSync(target, out)
console.log(`Wrote ${names.length} entities to ${target}`)
